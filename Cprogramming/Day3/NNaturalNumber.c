// Write a program to print the first 10 natural numbers using for loop.
#include<stdio.h>
int main(){
    for(int i=1;i<=10;i++){
        printf("%d\n",i);
    }
    //print numbers from 10 to 1
    printf("Numbers from 10 to 1");
    for(int i=10;i>=1;i--){
        printf("%d\n",i);
    }
    return 0;
}


